<?php

use App\Modules\Billing\Models\Invoice;
use App\Modules\Customer\Models\Customer;
use App\Modules\Customer\Models\CustomerServiceSubscription;
use App\Modules\Tenant\Models\Tenant;
use Faker\Factory as Faker;

$faker = Faker::create();
$tenant = Tenant::first();

$customers = Customer::all();
$subscriptions = CustomerServiceSubscription::all();

if ($customers->isEmpty()) {
    echo "No customers found. Run customer seeder first.\n";
    exit;
}

$types = ['subscription', 'subscription', 'installation', 'hardware'];
$statuses = ['issued', 'issued', 'paid', 'paid', 'partially_paid', 'draft', 'cancelled'];

$latest = Invoice::orderBy('id', 'desc')->first();
$startId = $latest ? $latest->id + 1 : 1;

for($i = 0; $i < 30; $i++) {
    $customer = $customers->random();
    $subscription = $subscriptions->where('customer_id', $customer->id)->first();
    
    $type = $faker->randomElement($types);
    $status = $faker->randomElement($statuses);
    
    $subtotal = $faker->numberBetween(500, 5000);
    $tax = $subtotal * 0.05; // 5% VAT
    $discount = $faker->boolean(20) ? $faker->numberBetween(50, 200) : 0;
    
    $grandTotal = $subtotal + $tax - $discount;
    
    if ($status === 'paid') {
        $amountPaid = $grandTotal;
        $amountDue = 0;
    } elseif ($status === 'partially_paid') {
        $amountPaid = round($grandTotal / 2, 2);
        $amountDue = $grandTotal - $amountPaid;
    } else {
        $amountPaid = 0;
        $amountDue = $grandTotal;
    }
    
    $invoiceNumber = 'INV-' . date('Y') . '-' . str_pad((string)($startId + $i), 5, '0', STR_PAD_LEFT);
    $issueDate = $faker->dateTimeBetween('-2 months', 'now');
    $dueDate = (clone $issueDate)->modify('+7 days');
    
    Invoice::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'customer_id' => $customer->id,
        'customer_service_subscription_id' => $subscription ? $subscription->id : null,
        'invoice_number' => $invoiceNumber,
        'invoice_type' => $type,
        'issue_date' => $issueDate->format('Y-m-d'),
        'due_date' => $dueDate->format('Y-m-d'),
        'currency' => 'BDT',
        'subtotal' => $subtotal,
        'tax_total' => $tax,
        'discount_total' => $discount,
        'grand_total' => $grandTotal,
        'amount_paid' => $amountPaid,
        'amount_due' => $amountDue,
        'billing_period_start' => $type === 'subscription' ? $issueDate->format('Y-m-d') : null,
        'billing_period_end' => $type === 'subscription' ? (clone $issueDate)->modify('+1 month')->format('Y-m-d') : null,
        'status' => $status,
        'notes' => 'Generated by Antigravity seeder.',
    ]);
}

echo "30 Demo invoices generated successfully.\n";
