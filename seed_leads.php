<?php

use App\Modules\CRM\Models\Lead;
use Faker\Factory as Faker;
use App\Modules\Tenant\Models\Tenant;

$faker = Faker::create();
$tenant = Tenant::first();
$statuses = ['new', 'contacted', 'survey_pending', 'proposal_sent', 'won', 'lost'];

for($i = 0; $i < 15; $i++) {
    $status = $faker->randomElement($statuses);
    Lead::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'first_name' => $faker->firstName,
        'last_name' => $faker->lastName,
        'phone' => '01' . $faker->numerify('#########'),
        'email' => $faker->unique()->safeEmail,
        'address' => $faker->address,
        'status' => $status,
        'expected_plan_id' => null, // Set to null to avoid foreign key issues if packages don't exist
        'notes' => 'Generated by Antigravity demo seeder.',
        'is_converted' => $status === 'won',
    ]);
}

echo "Demo leads generated successfully.\n";
