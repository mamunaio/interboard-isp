<?php

use App\Modules\Customer\Models\Customer;
use Faker\Factory as Faker;
use App\Modules\Tenant\Models\Tenant;

$faker = Faker::create();
$tenant = Tenant::first();
$types = ['residential', 'business', 'enterprise'];
$statuses = ['active', 'suspended', 'active', 'active', 'disconnected']; // Biased towards active

// Get the latest customer to generate sequential IDs
$latest = Customer::orderBy('id', 'desc')->first();
$startId = $latest ? $latest->id + 1 : 1;

for($i = 0; $i < 20; $i++) {
    $type = $faker->randomElement($types);
    $status = $faker->randomElement($statuses);
    
    $code = 'CUST-' . date('Y') . '-' . str_pad((string)($startId + $i), 5, '0', STR_PAD_LEFT);
    
    Customer::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'customer_code' => $code,
        'type' => $type,
        'full_name' => $faker->name,
        'company_name' => $type !== 'residential' ? $faker->company : null,
        'phone' => '01' . $faker->numerify('#########'),
        'alternate_phone' => $faker->boolean(30) ? '01' . $faker->numerify('#########') : null,
        'email' => $faker->unique()->safeEmail,
        'national_id' => $faker->numerify('##########'),
        'business_registration' => $type !== 'residential' ? $faker->numerify('BIN-########') : null,
        'date_of_birth' => $faker->dateTimeBetween('-50 years', '-18 years')->format('Y-m-d'),
        'notes' => 'Generated by Antigravity demo seeder.',
        'tags' => $faker->boolean(50) ? [$faker->word, $faker->word] : [],
        'referral_source' => $faker->randomElement(['Facebook', 'Google', 'Friend', 'Flyer', 'Sales Rep']),
        'status' => $status,
    ]);
}

echo "20 Demo customers generated successfully.\n";
