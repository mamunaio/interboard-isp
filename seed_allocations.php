<?php

use App\Modules\Billing\Models\PaymentAllocation;
use App\Modules\Billing\Models\PaymentReceipt;
use App\Modules\Billing\Models\Invoice;
use App\Modules\Billing\Models\Wallet;
use App\Modules\Billing\Models\LedgerEntry;
use App\Modules\Customer\Models\Customer;
use App\Modules\Tenant\Models\Tenant;
use Faker\Factory as Faker;

$faker = Faker::create();
$tenant = Tenant::first();

// Only select invoices that are 'paid' or 'partially_paid'
$invoices = Invoice::whereIn('status', ['paid', 'partially_paid'])->get();

if ($invoices->isEmpty()) {
    echo "No paid invoices found to create allocations for.\n";
    exit;
}

$latestReceipt = PaymentReceipt::orderBy('id', 'desc')->first();
$startReceiptId = $latestReceipt ? $latestReceipt->id + 1 : 1;

foreach ($invoices as $index => $invoice) {
    $customer = $invoice->customer;
    $wallet = Wallet::where('owner_type', Customer::class)->where('owner_id', $customer->id)->first();
    
    if (!$wallet) continue;

    $receiptNumber = 'RCPT-' . date('Y') . '-' . str_pad((string)($startReceiptId + $index), 6, '0', STR_PAD_LEFT);
    $amount = $invoice->amount_paid;

    // 1. Create Ledger Entry for the payment receipt (Credit to Wallet)
    $ledgerEntry = LedgerEntry::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'wallet_id' => $wallet->id,
        'transaction_type' => 'manual_payment_receipt',
        'direction' => 'credit',
        'amount' => $amount,
        'balance_before' => $wallet->current_balance,
        'balance_after' => $wallet->current_balance + $amount,
        'reference_type' => null, // We'll update this after receipt creation if it's nullable, or just leave it for demo
        'reference_id' => null,
        'idempotency_key' => \Illuminate\Support\Str::uuid(),
        'notes' => 'Ledger entry for receipt ' . $receiptNumber,
        'metadata' => [],
    ]);
    
    // Update wallet balance temporarily for the credit
    $wallet->current_balance += $amount;
    $wallet->save();

    // 2. Create Receipt
    $receipt = PaymentReceipt::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'customer_id' => $customer->id,
        'receipt_number' => $receiptNumber,
        'payment_method' => $faker->randomElement(['cash', 'bank_transfer', 'mobile_banking_manual']),
        'amount' => $amount,
        'currency' => 'BDT',
        'reference' => 'Payment for ' . $invoice->invoice_number,
        'notes' => 'Generated by Antigravity seeder.',
        'status' => 'posted',
        'wallet_ledger_entry_id' => $ledgerEntry->id,
    ]);
    
    // Update ledger entry reference
    $ledgerEntry->reference_type = PaymentReceipt::class;
    $ledgerEntry->reference_id = $receipt->id;
    $ledgerEntry->save();

    // 3. Create Ledger Entry for the Allocation (Debit from Wallet)
    $allocationLedgerEntry = LedgerEntry::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'wallet_id' => $wallet->id,
        'transaction_type' => 'payment_allocation',
        'direction' => 'debit',
        'amount' => $amount,
        'balance_before' => $wallet->current_balance,
        'balance_after' => $wallet->current_balance - $amount,
        'reference_type' => null, 
        'reference_id' => null,
        'idempotency_key' => \Illuminate\Support\Str::uuid(),
        'notes' => 'Allocation for invoice ' . $invoice->invoice_number,
        'metadata' => [],
    ]);
    
    // Update wallet balance back for the debit
    $wallet->current_balance -= $amount;
    $wallet->save();

    // 4. Create Allocation
    $allocation = PaymentAllocation::create([
        'tenant_id' => $tenant ? $tenant->id : null,
        'invoice_id' => $invoice->id,
        'wallet_id' => $wallet->id,
        'ledger_entry_id' => $allocationLedgerEntry->id,
        'payment_receipt_id' => $receipt->id,
        'allocation_amount' => $amount,
        'allocation_order' => 1,
        'idempotency_key' => \Illuminate\Support\Str::uuid(),
        'notes' => 'Automatic allocation for receipt ' . $receiptNumber . '.',
        'metadata' => [],
    ]);
    
    // Update allocation ledger entry reference
    $allocationLedgerEntry->reference_type = PaymentAllocation::class;
    $allocationLedgerEntry->reference_id = $allocation->id;
    $allocationLedgerEntry->save();
}

echo "Demo payment allocations generated successfully.\n";
